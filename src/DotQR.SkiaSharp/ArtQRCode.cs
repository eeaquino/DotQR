using SkiaSharp;
using static DotQR.ArtQRCode;
using static DotQR.QRCodeGenerator;

// pull request raised to extend library used.
namespace DotQR;

/// <summary>
/// Represents an art-style QR code generator that provides functionality to render QR codes with dots as modules.
/// </summary>
public class ArtQRCode : AbstractQRCode, IDisposable
{
    /// <summary>
    /// Initializes a new instance of the <see cref="ArtQRCode"/> class.
    /// Constructor without params to be used in COM Objects connections
    /// </summary>
    public ArtQRCode() { }

    /// <summary>
    /// Initializes a new instance of the <see cref="ArtQRCode"/> class with the specified <see cref="QRCodeData"/>.
    /// </summary>
    /// <param name="data"><see cref="QRCodeData"/> generated by the <see cref="QRCodeGenerator"/>.</param>
    public ArtQRCode(QRCodeData data) : base(data) { }

    /// <summary>
    /// Renders an art-style QR code with dots as modules. (With default settings: DarkColor=Black, LightColor=White, Background=Transparent, QuietZone=true)
    /// </summary>
    /// <param name="pixelsPerModule">Amount of px each dark/light module of the QR code shall take place in the final QR code image</param>
    /// <returns>QRCode graphic as bitmap</returns>
    public SKBitmap GetGraphic(int pixelsPerModule)
        => GetGraphic(pixelsPerModule, SKColors.Black, SKColors.White, SKColors.Transparent);

    /// <summary>
    /// Renders an art-style QR code with dots as modules and a background image (With default settings: DarkColor=Black, LightColor=White, Background=Transparent, QuietZone=true)
    /// </summary>
    /// <param name="backgroundImage">A bitmap object that will be used as background picture</param>
    /// <returns>QRCode graphic as bitmap</returns>
    public SKBitmap GetGraphic(SKBitmap? backgroundImage = null)
        => GetGraphic(10, SKColors.Black, SKColors.White, SKColors.Transparent, backgroundImage: backgroundImage);

    /// <summary>
    /// Renders an art-style QR code with dots as modules and various user settings
    /// </summary>
    /// <param name="pixelsPerModule">Amount of px each dark/light module of the QR code shall take place in the final QR code image</param>
    /// <param name="darkColor">Color of the dark modules</param>
    /// <param name="lightColor">Color of the light modules</param>
    /// <param name="backgroundColor">Color of the background</param>
    /// <param name="backgroundImage">A bitmap object that will be used as background picture</param>
    /// <param name="pixelSizeFactor">Value between 0.0 and 1.0 that defines each circular dot's diameter relative to its module. Dots remain circular at every size.</param>
    /// <param name="drawQuietZones">If true a white border is drawn around the whole QR Code</param>
    /// <param name="quietZoneRenderingStyle">Style of the quiet zones</param>
    /// <param name="backgroundImageStyle">Style of the background image (if set). Fill=spanning complete graphic; DataAreaOnly=Don't paint background into quietzone</param>
    /// <param name="finderPatternImage">Optional image that should be used instead of the default finder patterns</param>
    /// <returns>QRCode graphic as bitmap</returns>
    public SKBitmap GetGraphic(int pixelsPerModule, SKColor darkColor, SKColor lightColor, SKColor backgroundColor, SKBitmap? backgroundImage = null, double pixelSizeFactor = 1,
                               bool drawQuietZones = true, QuietZoneStyle quietZoneRenderingStyle = QuietZoneStyle.Dotted,
                               BackgroundImageStyle backgroundImageStyle = BackgroundImageStyle.DataAreaOnly, SKBitmap? finderPatternImage = null)
        => GetGraphic(pixelsPerModule, FinderPatternShape.Square, darkColor, lightColor, backgroundColor, backgroundImage,
            pixelSizeFactor, drawQuietZones, quietZoneRenderingStyle, backgroundImageStyle, finderPatternImage);

    /// <summary>
    /// Renders an art-style QR code using the selected shape for all three finder patterns.
    /// Custom finder-pattern images take precedence over the shape. Other settings match the existing overload.
    /// </summary>
    /// <param name="pixelsPerModule">Size of each module in pixels.</param>
    /// <param name="finderPatternShape">Shape of the outer rings and centers.</param>
    /// <param name="darkColor">Color of dark modules.</param>
    /// <param name="lightColor">Color of light modules.</param>
    /// <param name="backgroundColor">Background color.</param>
    /// <param name="backgroundImage">Optional background image.</param>
    /// <param name="pixelSizeFactor">Circular data-dot diameter relative to its module.</param>
    /// <param name="drawQuietZones">Whether to include quiet zones.</param>
    /// <param name="quietZoneRenderingStyle">Quiet-zone rendering style.</param>
    /// <param name="backgroundImageStyle">Background-image placement.</param>
    /// <param name="finderPatternImage">Optional image replacing all finder patterns.</param>
    /// <returns>QR code bitmap.</returns>
    public SKBitmap GetGraphic(int pixelsPerModule, FinderPatternShape finderPatternShape, SKColor darkColor, SKColor lightColor, SKColor backgroundColor,
        SKBitmap? backgroundImage = null, double pixelSizeFactor = 1, bool drawQuietZones = true,
        QuietZoneStyle quietZoneRenderingStyle = QuietZoneStyle.Dotted, BackgroundImageStyle backgroundImageStyle = BackgroundImageStyle.DataAreaOnly,
        SKBitmap? finderPatternImage = null)
    {
        if (finderPatternShape is not (FinderPatternShape.Square or FinderPatternShape.Circle or FinderPatternShape.RoundedSquare))
            throw new ArgumentOutOfRangeException(nameof(finderPatternShape));
        if (pixelSizeFactor > 1)
            throw new ArgumentOutOfRangeException(nameof(pixelSizeFactor), "The parameter pixelSizeFactor must be between 0 and 1. (0-100%)");
        var pixelSize = (float)(pixelsPerModule * pixelSizeFactor);

        var numModules = QrCodeData.ModuleMatrix.Count - (drawQuietZones ? 0 : 8);
        var offset = drawQuietZones ? 0 : 4;
        var size = numModules * pixelsPerModule;

        var bitmap = new SKBitmap(new SKImageInfo(size, size, SKColorType.Rgba8888, SKAlphaType.Premul));
        using var canvas = new SKCanvas(bitmap);
        using var flatPaint = new SKPaint { IsAntialias = false };
        using var dotPaint = new SKPaint { IsAntialias = true };
        using var imagePaint = new SKPaint { IsAntialias = true };

        canvas.Clear(backgroundColor);

        if (backgroundImage != null)
        {
            var sampling = new SKSamplingOptions(SKCubicResampler.Mitchell);
            if (backgroundImageStyle == BackgroundImageStyle.Fill)
            {
                canvas.DrawBitmap(backgroundImage, FitWithin(backgroundImage, SKRect.Create(0, 0, size, size)), sampling, imagePaint);
            }
            else if (backgroundImageStyle == BackgroundImageStyle.DataAreaOnly)
            {
                var bgOffset = 4 - offset;
                var target = size - (2 * bgOffset * pixelsPerModule);
                var area = SKRect.Create(bgOffset * pixelsPerModule, bgOffset * pixelsPerModule, target, target);
                canvas.DrawBitmap(backgroundImage, FitWithin(backgroundImage, area), sampling, imagePaint);
            }
        }

        // Keep each dot an independent circle. A compound path changes edge coverage where
        // circles touch, producing clipped-looking edges and uneven antialiasing.
        // Paint light circles first so they cannot overwrite a dark circle's edge coverage.
        var drawLightDots = lightColor != backgroundColor;
        var lightDots = new List<SKPoint>();
        var darkDots = new List<SKPoint>();
        var radius = pixelSize / 2f;
        var centre = pixelsPerModule / 2f;

        for (var x = 0; x < numModules; x++)
        {
            for (var y = 0; y < numModules; y++)
            {
                var rectangle = SKRect.Create(x * pixelsPerModule, y * pixelsPerModule, pixelsPerModule, pixelsPerModule);
                var pixelIsDark = QrCodeData.ModuleMatrix[offset + y][offset + x];

                if (!IsPartOfFinderPattern(x, y, numModules, offset))
                {
                    if (drawQuietZones && quietZoneRenderingStyle == QuietZoneStyle.Flat && IsPartOfQuietZone(x, y, numModules))
                    {
                        flatPaint.Color = pixelIsDark ? darkColor : lightColor;
                        canvas.DrawRect(rectangle, flatPaint);
                    }
                    else if (pixelSize > 0 && (pixelIsDark || drawLightDots))
                    {
                        var dots = pixelIsDark ? darkDots : lightDots;
                        dots.Add(new SKPoint(x * pixelsPerModule + centre, y * pixelsPerModule + centre));
                    }
                }
                else if (finderPatternImage == null && finderPatternShape == FinderPatternShape.Square)
                {
                    flatPaint.Color = pixelIsDark ? darkColor : lightColor;
                    canvas.DrawRect(rectangle, flatPaint);
                }
            }
        }

        dotPaint.Color = lightColor;
        foreach (var point in lightDots)
            canvas.DrawCircle(point, radius, dotPaint);

        dotPaint.Color = darkColor;
        foreach (var point in darkDots)
            canvas.DrawCircle(point, radius, dotPaint);

        if (finderPatternImage != null)
        {
            var sampling = new SKSamplingOptions(SKCubicResampler.Mitchell);
            var finderPatternSize = 7 * pixelsPerModule;
            var finderPatternOffset = drawQuietZones ? 4 * pixelsPerModule : 0;
            canvas.DrawBitmap(finderPatternImage, SKRect.Create(finderPatternOffset, finderPatternOffset, finderPatternSize, finderPatternSize), sampling, imagePaint);
            canvas.DrawBitmap(finderPatternImage, SKRect.Create(size - finderPatternOffset - finderPatternSize, finderPatternOffset, finderPatternSize, finderPatternSize), sampling, imagePaint);
            canvas.DrawBitmap(finderPatternImage, SKRect.Create(finderPatternOffset, size - finderPatternOffset - finderPatternSize, finderPatternSize, finderPatternSize), sampling, imagePaint);
        }

        else if (finderPatternShape != FinderPatternShape.Square)
        {
            var start = drawQuietZones ? 4 * pixelsPerModule : 0;
            var far = size - start - 7 * pixelsPerModule;
            DrawFinderPattern(canvas, start, start, pixelsPerModule, finderPatternShape, darkColor, lightColor);
            DrawFinderPattern(canvas, far, start, pixelsPerModule, finderPatternShape, darkColor, lightColor);
            DrawFinderPattern(canvas, start, far, pixelsPerModule, finderPatternShape, darkColor, lightColor);
        }

        return bitmap;
    }

    private static void DrawFinderPattern(SKCanvas canvas, int x, int y, int scale, FinderPatternShape shape, SKColor dark, SKColor light)
    {
        using var darkBuilder = new SKPathBuilder { FillType = SKPathFillType.EvenOdd };
        AddContour(SKRect.Create(x, y, 7 * scale, 7 * scale), 2 * scale);
        AddContour(SKRect.Create(x + scale, y + scale, 5 * scale, 5 * scale), scale);
        AddContour(SKRect.Create(x + 2 * scale, y + 2 * scale, 3 * scale, 3 * scale), scale);

        // Derive both colors from the SAME antialiased coverage on an isolated layer.
        // Independently rasterizing inverse paths can leave seams from different edge coverage.
        using var darkPath = darkBuilder.Detach();
        var bounds = SKRect.Create(x, y, 7 * scale, 7 * scale);
        using var paint = new SKPaint { Color = light };
        canvas.SaveLayer(bounds, null);
        canvas.DrawRect(bounds, paint);
        paint.IsAntialias = true;
        paint.Color = SKColors.White;
        paint.BlendMode = SKBlendMode.DstOut;
        canvas.DrawPath(darkPath, paint);
        paint.Color = dark;
        paint.BlendMode = SKBlendMode.Plus;
        canvas.DrawPath(darkPath, paint);
        canvas.Restore();

        void AddContour(SKRect bounds, float radius)
        {
            if (shape == FinderPatternShape.Circle)
                darkBuilder.AddOval(bounds);
            else
                darkBuilder.AddRoundRect(bounds, radius, radius);
        }
    }

    /// <summary>
    /// Shapes available for the three finder-pattern rings and centers.
    /// </summary>
    public enum FinderPatternShape
    {
        /// <summary>Traditional square finder patterns.</summary>
        Square,
        /// <summary>Circular finder-pattern rings and centers.</summary>
        Circle,
        /// <summary>Square finder-pattern rings and centers with rounded corners.</summary>
        RoundedSquare
    }

    /// <summary>
    /// Centres an image inside a square area, preserving its aspect ratio.
    /// </summary>
    /// <param name="image">The image to place.</param>
    /// <param name="area">The square area to place it in.</param>
    /// <returns>The destination rectangle for the draw call.</returns>
    private static SKRect FitWithin(SKBitmap image, SKRect area)
    {
        var scale = Math.Min(area.Width / image.Width, area.Height / image.Height);
        var width = image.Width * scale;
        var height = image.Height * scale;
        return SKRect.Create(
            area.Left + (area.Width - width) / 2f,
            area.Top + (area.Height - height) / 2f,
            width,
            height);
    }

    /// <summary>
    /// Checks if a given module(-position) is part of the quietzone of a QR code
    /// </summary>
    /// <param name="x">X position</param>
    /// <param name="y">Y position</param>
    /// <param name="numModules">Total number of modules per row</param>
    /// <returns>true, if position is part of quiet zone</returns>
    private static bool IsPartOfQuietZone(int x, int y, int numModules)
    {
        return
            x < 4 || //left
            y < 4 || //top
            x > numModules - 5 || //right
            y > numModules - 5; //bottom
    }

    /// <summary>
    /// Checks if a given module(-position) is part of one of the three finder patterns of a QR code
    /// </summary>
    /// <param name="x">X position</param>
    /// <param name="y">Y position</param>
    /// <param name="numModules">Total number of modules per row</param>
    /// <param name="offset">Offset in modules (usually depending on drawQuietZones parameter)</param>
    /// <returns>true, if position is part of any finder pattern</returns>
    private static bool IsPartOfFinderPattern(int x, int y, int numModules, int offset)
    {
        var cornerSize = 11 - offset;
        var outerLimitLow = (numModules - cornerSize - 1);
        var outerLimitHigh = outerLimitLow + 8;
        var invertedOffset = 4 - offset;
        return
            (x >= invertedOffset && x < cornerSize && y >= invertedOffset && y < cornerSize) || //Top-left finder pattern
            (x > outerLimitLow && x < outerLimitHigh && y >= invertedOffset && y < cornerSize) || //Top-right finder pattern
            (x >= invertedOffset && x < cornerSize && y > outerLimitLow && y < outerLimitHigh); //Bottom-left finder pattern
    }

    /// <summary>
    /// Defines how the quiet zones shall be rendered.
    /// </summary>
    public enum QuietZoneStyle
    {
        /// <summary>
        /// Quiet zones are rendered with dotted modules.
        /// </summary>
        Dotted,

        /// <summary>
        /// Quiet zones are rendered with flat, solid modules.
        /// </summary>
        Flat
    }

    /// <summary>
    /// Defines how the background image (if set) shall be rendered.
    /// </summary>
    public enum BackgroundImageStyle
    {
        /// <summary>
        /// Background image spans the complete graphic.
        /// </summary>
        Fill,

        /// <summary>
        /// Background image is only painted in the data area, excluding the quiet zone.
        /// </summary>
        DataAreaOnly
    }
}

/// <summary>
/// Provides static methods for creating art-style QR codes.
/// </summary>
public static class ArtQRCodeHelper
{
    /// <summary>
    /// Helper function to create an ArtQRCode graphic with a single function call
    /// </summary>
    /// <param name="plainText">Text/payload to be encoded inside the QR code</param>
    /// <param name="pixelsPerModule">Amount of px each dark/light module of the QR code shall take place in the final QR code image</param>
    /// <param name="darkColor">Color of the dark modules</param>
    /// <param name="lightColor">Color of the light modules</param>
    /// <param name="backgroundColor">Color of the background</param>
    /// <param name="eccLevel">The level of error correction data</param>
    /// <param name="forceUtf8">Shall the generator be forced to work in UTF-8 mode?</param>
    /// <param name="utf8BOM">Should the byte-order-mark be used?</param>
    /// <param name="eciMode">Which ECI mode shall be used?</param>
    /// <param name="requestedVersion">Set fixed QR code target version.</param>
    /// <param name="backgroundImage">A bitmap object that will be used as background picture</param>
    /// <param name="pixelSizeFactor">Value between 0.0 and 1.0 that defines each circular dot's diameter relative to its module. Dots remain circular at every size.</param>
    /// <param name="drawQuietZones">If true a white border is drawn around the whole QR Code</param>
    /// <param name="quietZoneRenderingStyle">Style of the quiet zones</param>
    /// <param name="backgroundImageStyle">Style of the background image (if set). Fill=spanning complete graphic; DataAreaOnly=Don't paint background into quietzone</param>
    /// <param name="finderPatternImage">Optional image that should be used instead of the default finder patterns</param>
    /// <returns>QRCode graphic as bitmap</returns>
    public static SKBitmap GetQRCode(string plainText, int pixelsPerModule, SKColor darkColor, SKColor lightColor, SKColor backgroundColor, ECCLevel eccLevel, bool forceUtf8 = false,
                                     bool utf8BOM = false, EciMode eciMode = EciMode.Default, int requestedVersion = -1, SKBitmap? backgroundImage = null, double pixelSizeFactor = 1.0,
                                     bool drawQuietZones = true, QuietZoneStyle quietZoneRenderingStyle = QuietZoneStyle.Flat,
                                     BackgroundImageStyle backgroundImageStyle = BackgroundImageStyle.DataAreaOnly, SKBitmap? finderPatternImage = null)
    {
        using var qrGenerator = new QRCodeGenerator();
        using var qrCodeData = qrGenerator.CreateQrCode(plainText, eccLevel, forceUtf8, utf8BOM, eciMode, requestedVersion);
        using var qrCode = new ArtQRCode(qrCodeData);
        return qrCode.GetGraphic(pixelsPerModule, darkColor, lightColor, backgroundColor, backgroundImage, pixelSizeFactor, drawQuietZones, quietZoneRenderingStyle, backgroundImageStyle, finderPatternImage);
    }
}

using SkiaSharp;
using static DotQR.QRCodeGenerator;

namespace DotQR;

/// <summary>
/// Represents a QR code generator that outputs QR codes as bitmap images.
/// </summary>
public class QRCode : AbstractQRCode, IDisposable
{
    /// <summary>
    /// Initializes a new instance of the <see cref="QRCode"/> class.
    /// Constructor without parameters to be used in COM objects connections.
    /// </summary>
    public QRCode() { }

    /// <summary>
    /// Initializes a new instance of the <see cref="QRCode"/> class with the specified <see cref="QRCodeData"/>.
    /// </summary>
    /// <param name="data"><see cref="QRCodeData"/> generated by the QRCodeGenerator.</param>
    public QRCode(QRCodeData data) : base(data) { }

    /// <summary>
    /// Creates a black and white bitmap image of the QR code.
    /// </summary>
    /// <param name="pixelsPerModule">The number of pixels each dark/light module of the QR code will occupy in the final QR code image.</param>
    /// <returns>Returns the QR code graphic as a bitmap.</returns>
    public SKBitmap GetGraphic(int pixelsPerModule)
        => GetGraphic(pixelsPerModule, SKColors.Black, SKColors.White, true);

    /// <summary>
    /// Creates a colored bitmap image of the QR code.
    /// </summary>
    /// <param name="pixelsPerModule">The number of pixels each dark/light module of the QR code will occupy in the final QR code image.</param>
    /// <param name="darkColorHtmlHex">The color of the dark modules in HTML hex format or as an HTML color name.</param>
    /// <param name="lightColorHtmlHex">The color of the light modules in HTML hex format or as an HTML color name.</param>
    /// <param name="drawQuietZones">Indicates if quiet zones around the QR code should be drawn.</param>
    /// <returns>Returns the QR code graphic as a bitmap.</returns>
    public SKBitmap GetGraphic(int pixelsPerModule, string darkColorHtmlHex, string lightColorHtmlHex, bool drawQuietZones = true)
        => GetGraphic(
            pixelsPerModule,
            RgbaColor.Parse(darkColorHtmlHex).ToSKColor(),
            RgbaColor.Parse(lightColorHtmlHex).ToSKColor(),
            drawQuietZones);

    /// <summary>
    /// Creates a colored bitmap image of the QR code.
    /// </summary>
    /// <param name="pixelsPerModule">The number of pixels each dark/light module of the QR code will occupy in the final QR code image.</param>
    /// <param name="darkColor">The color of the dark modules.</param>
    /// <param name="lightColor">The color of the light modules.</param>
    /// <param name="drawQuietZones">Indicates if quiet zones around the QR code should be drawn.</param>
    /// <returns>Returns the QR code graphic as a bitmap.</returns>
    public SKBitmap GetGraphic(int pixelsPerModule, SKColor darkColor, SKColor lightColor, bool drawQuietZones = true)
        => GetGraphic(pixelsPerModule, darkColor, lightColor, null, 0, 0, drawQuietZones, null);

    /// <summary>
    /// Creates a colored bitmap image of the QR code with an optional icon in the center.
    /// </summary>
    /// <param name="pixelsPerModule">The number of pixels each dark/light module of the QR code will occupy in the final QR code image.</param>
    /// <param name="darkColor">The color of the dark modules.</param>
    /// <param name="lightColor">The color of the light modules.</param>
    /// <param name="icon">An optional icon to be placed in the center of the QR code.</param>
    /// <param name="iconSizePercent">The size of the icon as a percentage of the QR code size.</param>
    /// <param name="iconBorderWidth">The width of the border around the icon.</param>
    /// <param name="drawQuietZones">Indicates if quiet zones around the QR code should be drawn.</param>
    /// <param name="iconBackgroundColor">The background color of the icon.</param>
    /// <returns>Returns the QR code graphic as a bitmap.</returns>
    public SKBitmap GetGraphic(int pixelsPerModule, SKColor darkColor, SKColor lightColor, SKBitmap? icon = null, int iconSizePercent = 15, int iconBorderWidth = 0, bool drawQuietZones = true, SKColor? iconBackgroundColor = null)
    {
        var moduleCount = QrCodeData.ModuleMatrix.Count - (drawQuietZones ? 0 : 8);
        var startIndex = drawQuietZones ? 0 : 4;
        var size = moduleCount * pixelsPerModule;

        // Render the matrix once at module resolution, then scale it up with nearest-neighbour
        // sampling. At integer scale that is pixel-exact, and it costs one blit instead of painting
        // hundreds of rectangles at the final resolution.
        using var modules = new SKBitmap(new SKImageInfo(moduleCount, moduleCount, SKColorType.Rgba8888, SKAlphaType.Premul));
        var matrix = QrCodeData.ModuleMatrix;
        for (var y = 0; y < moduleCount; y++)
        {
            var row = matrix[y + startIndex];
            for (var x = 0; x < moduleCount; x++)
            {
                modules.SetPixel(x, y, row[x + startIndex] ? darkColor : lightColor);
            }
        }

        var bitmap = new SKBitmap(new SKImageInfo(size, size, SKColorType.Rgba8888, SKAlphaType.Premul));
        using (var canvas = new SKCanvas(bitmap))
        using (var blitPaint = new SKPaint { IsAntialias = false, BlendMode = SKBlendMode.Src })
        {
            canvas.DrawBitmap(
                modules,
                SKRect.Create(0, 0, size, size),
                new SKSamplingOptions(SKFilterMode.Nearest, SKMipmapMode.None),
                blitPaint);

            var drawIconFlag = icon != null && iconSizePercent > 0 && iconSizePercent <= 100;
            if (drawIconFlag)
            {
                var iconWidth = size;
                var iconDestWidth = iconSizePercent * iconWidth / 100f;
                var iconDestHeight = iconDestWidth * icon!.Height / icon.Width;
                var iconX = (iconWidth - iconDestWidth) / 2;
                var iconY = (size - iconDestHeight) / 2;

                // Only render the icon background when a border was requested.
                if (iconBorderWidth > 0)
                {
                    using var backgroundPaint = new SKPaint { IsAntialias = true, Color = iconBackgroundColor ?? lightColor };
                    var radius = iconBorderWidth * 2;
                    var border = SKRect.Create(
                        iconX - iconBorderWidth,
                        iconY - iconBorderWidth,
                        iconDestWidth + iconBorderWidth * 2,
                        iconDestHeight + iconBorderWidth * 2);
                    canvas.DrawRoundRect(border, radius, radius, backgroundPaint);
                }

                using var iconPaint = new SKPaint { IsAntialias = true };
                using var iconImage = SKImage.FromBitmap(icon);
                canvas.DrawImage(
                    iconImage,
                    SKRect.Create(iconX, iconY, iconDestWidth, iconDestHeight),
                    new SKSamplingOptions(SKCubicResampler.Mitchell),
                    iconPaint);
            }
        }

        return bitmap;
    }
}

/// <summary>
/// Provides static methods for creating bitmap QR codes.
/// </summary>
public static class QRCodeHelper
{
    /// <summary>
    /// Creates a bitmap QR code with a single function call.
    /// </summary>
    /// <param name="plainText">The text or payload to be encoded inside the QR code.</param>
    /// <param name="pixelsPerModule">The number of pixels each dark/light module of the QR code will occupy in the final QR code image.</param>
    /// <param name="darkColor">The color of the dark modules.</param>
    /// <param name="lightColor">The color of the light modules.</param>
    /// <param name="eccLevel">The level of error correction data.</param>
    /// <param name="forceUtf8">Specifies whether the generator should be forced to work in UTF-8 mode.</param>
    /// <param name="utf8BOM">Specifies whether the byte-order-mark should be used.</param>
    /// <param name="eciMode">Specifies which ECI mode should be used.</param>
    /// <param name="requestedVersion">Sets the fixed QR code target version.</param>
    /// <param name="icon">An optional icon to be placed in the center of the QR code.</param>
    /// <param name="iconSizePercent">The size of the icon as a percentage of the QR code size.</param>
    /// <param name="iconBorderWidth">The width of the border around the icon.</param>
    /// <param name="drawQuietZones">Indicates if quiet zones around the QR code should be drawn.</param>
    /// <returns>Returns the QR code graphic as a bitmap.</returns>
    public static SKBitmap GetQRCode(string plainText, int pixelsPerModule, SKColor darkColor, SKColor lightColor, ECCLevel eccLevel, bool forceUtf8 = false, bool utf8BOM = false, EciMode eciMode = EciMode.Default, int requestedVersion = -1, SKBitmap? icon = null, int iconSizePercent = 15, int iconBorderWidth = 0, bool drawQuietZones = true)
    {
        using var qrGenerator = new QRCodeGenerator();
        using var qrCodeData = qrGenerator.CreateQrCode(plainText, eccLevel, forceUtf8, utf8BOM, eciMode, requestedVersion);
        using var qrCode = new QRCode(qrCodeData);
        return qrCode.GetGraphic(pixelsPerModule, darkColor, lightColor, icon, iconSizePercent, iconBorderWidth, drawQuietZones);
    }
}
